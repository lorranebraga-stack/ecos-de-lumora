// A fase é montada com 6 trechos de 30 colunas × 20 linhas (cada trecho ≈ uma tela).
// Legenda:
//   '#' rocha · '=' galho · '^' espinhos · 'P' início · 'F' saída · '.' vazio
//   'c' cristal · 'm' Murcho · 't' Traça-de-Cinza
//   'f' fragmento de memória · 'E' Pedra-Eco
//   'L' ponte latente · 'v' flor latente · 'X' parede falsa
//   'K' lanterna (checkpoint). Pedras-Eco ativadas também servem de checkpoint.
//
// Regras de projeto (a partir da física em config.js):
//   - O Nilo sobe com folga até 2 blocos (32 px). 3 blocos é o limite, evite.
//   - Andando, vence vãos de até 3 blocos; correndo, até 5 com folga (7 no limite).
//     Para um vão ser IMPOSSÍVEL, use 9 ou mais.
//   - Murcho precisa de chão embaixo; ele patrulha até uma parede, borda ou espinho.
//   - Blocos de memória e criaturas pertencem à Pedra-Eco MAIS PRÓXIMA.
//   - Cada fragmento fica no caminho, ANTES da pedra que ele abre.
//
// Arco da memória:  fragmento 1 → ponte (trecho 2)
//                   fragmento 2 → parede falsa (trecho 4)
//                   fragmento 3 → escada de flores até o alto do penhasco (trecho 6)
//                   chefe: Raiz Esquecida (trecho 7) → saída

